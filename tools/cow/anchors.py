"""anchors.py - the names xi-on-anything already gives FFXiMain addresses, as anchors for naming.

    python tools/cow/anchors.py            writes docs/cow/anchors.csv and docs/cow/ANCHORS.md

xi-on-anything does not decompile FFXiMain; its recompiler translates every function mechanically. What it
does know is WHERE things are: meta/builds.json names, per client build, the functions it wraps (packet
encryption, the chat line, input parsing), the sites it hooks inside functions, the globals it reads (the
character list, the scene manager), the UI manager's entries, the C runtime functions, and the bytes its
patches change. Each of those names is backed by working code - the port's own features call or hook
exactly that address - so it is the most reliable evidence we have for what a function is.

This reads them for the build generated/build.json names and writes, one row per address:
    va, name, group (wraps, hooks, addresses, modern, crt, patches), what (function: an entry; site: an
    address inside a function; global: data), function (the entry that contains it), unit (our unit file,
    if any), tier (its verdict).
A function anchor is a name for that function; a site anchor tells what one point inside it does; a global
anchor names data, so every function that reads it is easier to name. Nothing here changes a verdict or
the percentage: it is the starting set for the naming track. Run it again after a new build lands (the
addresses come from that build's own entry in meta/builds.json).
"""
import bisect
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GROUPS = ("wraps", "crt", "modern", "addresses", "hooks", "patches")


def main():
    build = json.load(open(os.path.join(ROOT, "generated", "build.json")))["build"]
    entry = json.load(open(os.path.join(ROOT, "meta", "builds.json")))["builds"][build]
    meta = json.load(open(os.path.join(ROOT, "meta", "FFXiMain.%s.meta.json" % build)))
    funcs = []
    for f in meta["functions"]:
        e = int(f["entry"], 16) if isinstance(f["entry"], str) else f["entry"]
        rs = [(int(a, 16) if isinstance(a, str) else a, int(b, 16) if isinstance(b, str) else b)
              for a, b in f["ranges"]]
        funcs.append((e, rs))
    entries = {e for e, _r in funcs}
    spans = sorted((a, b, e) for e, rs in funcs for a, b in rs)
    starts = [s[0] for s in spans]

    def owner(va):
        k = bisect.bisect_right(starts, va) - 1
        if k >= 0 and spans[k][0] <= va < spans[k][1]:
            return spans[k][2]
        return None

    led = {}
    p = os.path.join(ROOT, "cow", "lift_proof_all.json")
    if os.path.isfile(p):
        led = json.load(open(p, encoding="utf-8"))
    rows = []
    for group in GROUPS:
        items = entry.get(group) or {}
        for name, val in sorted(items.items()):
            vas = []
            if group == "patches":
                vas = [int(a, 16) for a in val] if isinstance(val, dict) else []
            elif isinstance(val, str) and val.startswith("0x"):
                vas = [int(val, 16)]
            for va in vas:
                fn = owner(va)
                what = "function" if va in entries else "site" if fn is not None else "global"
                h = "%08x" % fn if fn is not None else ""
                unit = "src/lifted/cow_%s.c" % h if h and os.path.isfile(
                    os.path.join(ROOT, "src", "lifted", "cow_%s.c" % h)) else ""
                rows.append({"va": "0x%08x" % va, "name": name, "group": group, "what": what,
                             "function": ("0x" + h) if h else "", "unit": unit,
                             "tier": (led.get(h) or {}).get("tier", "") if h else ""})
    os.makedirs(os.path.join(ROOT, "docs", "cow"), exist_ok=True)
    out = os.path.join(ROOT, "docs", "cow", "anchors.csv")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        w = csv.DictWriter(fh, fieldnames=["va", "name", "group", "what", "function", "unit", "tier"],
                           lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    named_funcs = {r["function"] for r in rows if r["function"]}
    by = {}
    for r in rows:
        by.setdefault((r["group"], r["what"]), 0)
        by[(r["group"], r["what"])] += 1
    lines = ["# Anchors from xi-on-anything", "",
             "Generated by `tools/cow/anchors.py` from `meta/builds.json` for build `%s`. Every row is an address "
             "the port's own code calls, hooks, reads or patches, so its name is backed by working code. "
             "The full list is [anchors.csv](anchors.csv)." % build, "",
             "**%d anchors, touching %d functions.**" % (len(rows), len(named_funcs)), "",
             "| group | what | count |", "| :-- | :-- | --: |"]
    for (g, wh), n in sorted(by.items()):
        lines.append("| %s | %s | %d |" % (g, wh, n))
    lines += ["", "## Function anchors (a name for the whole function)", "",
              "| address | name | group | unit | tier |", "| :-- | :-- | :-- | :-- | :-- |"]
    for r in rows:
        if r["what"] == "function":
            lines.append("| `%s` | %s | %s | %s | %s |" % (r["va"], r["name"], r["group"],
                                                          "yes" if r["unit"] else "", r["tier"]))
    lines += ["", "## Site anchors (what one point inside a function does)", "",
              "| address | name | group | in function | tier |", "| :-- | :-- | :-- | :-- | :-- |"]
    for r in rows:
        if r["what"] == "site":
            lines.append("| `%s` | %s | %s | `%s` | %s |" % (r["va"], r["name"], r["group"], r["function"], r["tier"]))
    lines += ["", "## Global anchors (named data)", "", "| address | name | group |", "| :-- | :-- | :-- |"]
    for r in rows:
        if r["what"] == "global":
            lines.append("| `%s` | %s | %s |" % (r["va"], r["name"], r["group"]))
    os.makedirs(os.path.join(ROOT, "docs", "cow"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "cow", "ANCHORS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("ANCHORS: %d rows (%s), %d functions touched -> docs/cow/anchors.csv, docs/cow/ANCHORS.md" % (
        len(rows), ", ".join("%s %d" % (g, sum(1 for r in rows if r["group"] == g)) for g in GROUPS),
        len(named_funcs)))


if __name__ == "__main__":
    main()
