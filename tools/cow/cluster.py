"""A unit is a CLUSTER, not an address: one object and the functions that touch it, or a caller and
its small callees.

    python tools/cow/cluster.py 0x100dbeb0            # what the net-clock cluster is
    python tools/cow/cluster.py 0x100dbeb0 --json
    python tools/cow/cluster.py --next                # grow a cluster around the next unit of work

Why: reading an entry costs a full pass over its generated body, its callees and its oracles, and the
second entry that touches the same struct costs nearly the same pass again - the context is already in
hand. One address per commit threw that away, and split one object across commits, which is also what
produced the follow-up "machinery" commits. One read, one commit, for the whole cluster.

Two relations grow a cluster, both read out of the generated bytes rather than guessed:

  callees   - f_<hex>(g) calls in the seed's own body that are small (<= --max-callee-bytes) and not
              thunks. A caller and the handful of 20-byte helpers it calls is one read.
  siblings  - entries whose bodies read the same absolute image address: the same global, or the same
              struct base. That is what "one object and the functions that touch it" means - the net
              clock is 0x100dbeb0 / 0x100dc1f0 / 0x100dc210 / 0x100dc250 / 0x100dc260 precisely because
              they all go through 0x10492e10.

An address only counts as the object if it is not code: any address inside some entry's [entry, end) is
a label or an immediate, not data. Without that filter a cluster swallows every function that happened
to mention a neighbouring address.

A cluster is capped (--max, default 6): past that it is a subsystem, and a subsystem read is not one
unit's work.
"""
import argparse
import bisect
import collections
import csv
import json
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import trivial_audit                      # noqa: E402  body_index(), one pass over generated/all

LEDGER = os.path.join(ROOT, 'ledger', 'functions.csv')

CALL_RE = re.compile(r'\bf_([0-9a-f]{8})\s*\(')
ABS_RE = re.compile(r'\b0x(10[0-9a-f]{6})\b')


def ledger_rows():
    with open(LEDGER, newline='', encoding='utf-8') as fh:
        return {r['entry'].lower().replace('0x', ''): r for r in csv.DictReader(fh)}


def code_ranges(rows):
    """Sorted (start, end) of every ledger entry, so a number can be tested for 'is this code?'."""
    out = []
    for e, r in rows.items():
        try:
            start = int(e, 16)
            size = int(r['size'] or 0)
        except ValueError:
            continue
        out.append((start, start + max(size, 1)))
    out.sort()
    return out


def is_code(addr, ranges):
    i = bisect.bisect_right(ranges, (addr, 0xFFFFFFFF)) - 1
    if i >= 0 and ranges[i][0] <= addr < ranges[i][1]:
        return True
    # also reject a bare entry start (size may be missing)
    j = bisect.bisect_left([s for s, _ in ranges], addr)
    return False


def texts_of(hex8):
    body = trivial_audit.body_index().get(hex8.lower().replace('0x', ''))
    if not body:
        return []
    return [l for l in body if '/*' in l]


def callees_of(hex8):
    out = set()
    for line in texts_of(hex8):
        for m in CALL_RE.finditer(line):
            if m.group(1) != hex8:
                out.add(m.group(1))
    return sorted(out)


def absolutes_of(hex8):
    out = set()
    for line in texts_of(hex8):
        for m in ABS_RE.finditer(line):
            out.add(m.group(1))
    return out


def _int(r, key):
    try:
        return int(r.get(key) or 0)
    except ValueError:
        return 0


def cluster(seed, rows, ranges, max_callee_bytes=64, max_members=6):
    """The cluster around `seed`.

    Members already `done` do not count against --max: they are not work, they are the context the read
    produces anyway, and dropping them means converting a function that shares an object with a
    converted sibling without knowing the sibling exists. --max caps the CONVERTIBLE members.
    """
    seed = seed.lower().replace('0x', '')
    members = collections.OrderedDict()
    members[seed] = 'seed'

    for c in callees_of(seed):
        r = rows.get(c)
        if r is None or r['status'] == 'thunk':
            continue
        size = _int(r, 'size')
        if 0 < size <= max_callee_bytes:
            members.setdefault(c, 'callee of %s (%dB)' % (seed, size))

    # the object: image addresses the seed reads that are NOT code
    object_addrs = {a for a in absolutes_of(seed)
                    if a not in rows and not is_code(int(a, 16), ranges)}
    if object_addrs:
        seednum = int(seed, 16)
        scored = []
        for other in rows:
            if other in members:
                continue
            hit = object_addrs & absolutes_of(other)
            if hit:
                r = rows.get(other) or {}
                if r.get('status') == 'thunk':
                    continue
                # already-converted first (they are the object's known shape), then nearest in the image:
                # the linker keeps one source file's functions together, so address distance is a cheap
                # proxy for "written next to each other, does the same thing"
                done_first = 0 if r.get('status') == 'done' else 1
                scored.append((done_first, abs(int(other, 16) - seednum), other))
        work = 0
        for _d, _dist, other in sorted(scored):
            r = rows.get(other) or {}
            convertible = r.get('status') in ('todo', 'in_progress', 'failed')
            if convertible and work >= max_members - 1:
                continue          # the cap counts work, not context
            if convertible:
                work += 1
            members.setdefault(other, 'shares %s with %s (%dB)'
                               % (','.join('0x' + a for a in
                                           sorted(object_addrs & absolutes_of(other))[:2]),
                                  seed, _int(r, 'size')))
    order = sorted(members.items(), key=lambda kv: (0 if kv[0] == seed else 1, kv[0]))
    return [{'entry': '0x' + e, 'why': w, 'status': (rows.get(e) or {}).get('status', '?'),
             'size': (rows.get(e) or {}).get('size', '?'),
             'name': (rows.get(e) or {}).get('name', '')}
            for e, w in order]


def parked():
    """cow/skip.txt: entries the loop has parked (no owner, or a body that must be written by hand).

    loopy honours this file and cluster.py must too, or `--next` grows a cluster around an entry that
    can never be booked - which is what two consecutive clusters did on 2026-11-05, each ending in a
    `failed` commit for a body nobody reaches.
    """
    path = os.path.join(ROOT, 'cow', 'skip.txt')
    if not os.path.isfile(path):
        return set()
    with open(path, encoding='utf-8', errors='replace') as fh:
        return {l.strip().lower().replace('0x', '') for l in fh
                if l.strip() and not l.startswith('#')}


def next_seed(rows):
    """The next unit of work: real size (>8B), lowest leaf_rank, then smallest, and not parked."""
    skip = parked()
    work = [r for e, r in rows.items()
            if r['status'] in ('todo', 'in_progress') and _int(r, 'size') > 8
            and r['entry'].lower().replace('0x', '') not in skip]
    work.sort(key=lambda r: (int(r['leaf_rank'] or 3), _int(r, 'size'), r['entry']))
    return work[0]['entry'] if work else None


def main():
    ap = argparse.ArgumentParser(prog='cluster.py')
    ap.add_argument('seed', nargs='?')
    ap.add_argument('--next', action='store_true', help='grow around the next unit of work')
    ap.add_argument('--max', type=int, default=6)
    ap.add_argument('--max-callee-bytes', type=int, default=64)
    ap.add_argument('--json', action='store_true')
    a = ap.parse_args()

    rows = ledger_rows()
    ranges = code_ranges(rows)
    seed = a.seed or (next_seed(rows) if a.next else None)
    if not seed:
        ap.error('give a seed, or --next')
    cs = cluster(seed, rows, ranges, a.max_callee_bytes, a.max)
    if a.json:
        print(json.dumps({'seed': seed, 'members': cs}, indent=1))
    else:
        print('cluster around %s (%d member(s)):' % (seed, len(cs)))
        for m in cs:
            print('   %-12s %-11s %-5s %-32s %s' % (m['entry'], m['status'], str(m['size']) + 'B',
                                                    m['name'] or '-', m['why']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
