#!/usr/bin/env python3
"""Write tools/cow/judge_import_pops.h: the imports whose shims the judge image does not link, with the
argument words each pops, for tools/cow/cowdiff.c to answer inside a state (judge 17).

    python tools/cow/mk_import_pops.py

The counts come from the runtime's own shims (`RET(v, n)`, read by rise.import_args); for the few the shims
do not say, from the Win32 ABI itself (WINSOCK's functions are WSAAPI = stdcall; wsprintfA is cdecl)."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'cow', 'rise'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))

# the runtime files the judge image links (tools/build.py PORTABLE, the portable runtime)
import build  # noqa: E402
LINKED = {os.path.basename(p.replace('\\', '/')) for p in build.PORTABLE} | {'thunk.c', 'pe.c', 'gwin.c', 'gthread.c'}

# the Win32 ABI, where the runtime's shim does not say (stdcall words; cdecl: the words a call passes at least)
ABI = {
    ('ws2_32.dll', 'recv'): 4, ('ws2_32.dll', 'send'): 4, ('ws2_32.dll', 'select'): 5, ('ws2_32.dll', 'listen'): 2,
    ('ws2_32.dll', 'accept'): 3, ('ws2_32.dll', 'sendto'): 6, ('ws2_32.dll', 'recvfrom'): 6,
    ('ws2_32.dll', 'WSAGetLastError'): 0, ('ws2_32.dll', 'bind'): 3, ('ws2_32.dll', 'ntohs'): 1,
    ('ws2_32.dll', 'setsockopt'): 5, ('ws2_32.dll', 'getsockopt'): 5, ('ws2_32.dll', 'ioctlsocket'): 3,
    ('ws2_32.dll', 'gethostname'): 2, ('ws2_32.dll', 'inet_ntoa'): 1, ('ws2_32.dll', 'gethostbyname'): 1,
    ('ws2_32.dll', 'htonl'): 1, ('ws2_32.dll', 'WSAStartup'): 2, ('ws2_32.dll', 'WSACleanup'): 0,
    ('ws2_32.dll', 'htons'): 1, ('ws2_32.dll', 'closesocket'): 1, ('ws2_32.dll', 'shutdown'): 2,
    ('ws2_32.dll', 'socket'): 3, ('ws2_32.dll', 'connect'): 3, ('ws2_32.dll', '__WSAFDIsSet'): 2,
    ('user32.dll', 'DrawTextA'): 5, ('user32.dll', 'DrawTextW'): 5,
}
CDECL = {('user32.dll', 'wsprintfA')}       # the caller cleans: pops 0

# WINSOCK IS IMPORTED BY ORDINAL: the runtime names the thunk "WS2_32.dll!#10", not ioctlsocket, so each
# entry is written under that name too (the standard WS2_32 ordinals), and DSOUND's DirectSoundCreate8 (#11)
ORDINALS = {
    'ws2_32.dll': {'accept': 1, 'bind': 2, 'closesocket': 3, 'connect': 4, 'getpeername': 5, 'getsockname': 6,
                   'getsockopt': 7, 'htonl': 8, 'htons': 9, 'ioctlsocket': 10, 'inet_addr': 11, 'inet_ntoa': 12,
                   'listen': 13, 'ntohl': 14, 'ntohs': 15, 'recv': 16, 'recvfrom': 17, 'select': 18, 'send': 19,
                   'sendto': 20, 'setsockopt': 21, 'shutdown': 22, 'socket': 23, 'gethostbyaddr': 51,
                   'gethostbyname': 52, 'gethostname': 57, 'WSAGetLastError': 111, 'WSAStartup': 115,
                   'WSACleanup': 116, '__WSAFDIsSet': 151},
}
ABI[('dsound.dll', 'ord11')] = 3                # DirectSoundCreate8(guid, out, outer)


def main():
    import rise
    import seek
    pops = rise.import_args(ROOT)
    where = {}
    for d, _, fs in os.walk(os.path.join(ROOT, 'runtime')):
        for f in fs:
            if f.endswith('.c'):
                t = open(os.path.join(d, f), encoding='utf-8', errors='replace').read()
                for m in re.finditer(r'\{\s*"([\w.]+)",\s*"(\w+)",\s*sh_\w+\s*\}', t):
                    where[(m.group(1).lower(), m.group(2))] = f
    img = seek.load_image(os.path.join(ROOT, 'generated', 'FFXiMain.unpacked.dll'))
    rows = []
    for dll, name in sorted({(d.lower(), n) for d, n in img.iat.values()}):
        f = where.get((dll, name))
        if f in LINKED:
            continue
        if (dll, name) in CDECL:
            n, pop = 0, 0
        else:
            n = pops.get((dll, name), ABI.get((dll, name)))
            pop = n
        if n is None:
            continue
        rows.append((dll, name, pop, f or 'no shim'))
    out = ['/* generated by tools/cow/mk_import_pops.py from the runtime\'s shims - do not edit by hand.',
           '   THE IMPORTS THE JUDGE DOES NOT LINK (judge 17): their shims are in runtime files the judge image leaves',
           '   out (user32.c, ws2.c, d3d8.c, dinput.c: SDL, sockets, devices), or there is none. Called inside a state',
           '   they ended it with "no shim yet" on both sides, and every instruction after such a call was a site no',
           '   state reached. Inside a state the harness answers them (tools/cow/cowdiff.c, import_answer): the',
           '   argument words the call pops, an answer from the state\'s stream, the same on both sides; the call is',
           '   logged like any other. */',
           'typedef struct CowImportPop { const char* name; unsigned pop_words; } CowImportPop;',
           'static const CowImportPop g_import_pops[] = {']
    for dll, name, pop, f in rows:
        out.append('    { "%s!%s", %du },   /* %s */' % (dll, name, pop, f))
        o = ORDINALS.get(dll, {}).get(name)
        if o is not None:
            out.append('    { "%s!#%d", %du },   /* %s, by ordinal */' % (dll, o, pop, name))
        if dll == 'dsound.dll' and name == 'ord11':
            out.append('    { "%s!#11", %du },   /* DirectSoundCreate8, by ordinal */' % (dll, pop))
    out += ['    { 0, 0u }', '};']
    with open(os.path.join(ROOT, 'tools', 'cow', 'judge_import_pops.h'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%d imports answered by the harness' % len(rows))


if __name__ == '__main__':
    main()
