"""Generate cow/wraps.json and runtime/cow/cow_wraps.c from the ledger. Never edit either by hand.

The ledger (ledger/functions.csv) is the state; these two files are its projection onto upstream's
`recomp.py --wraps` mechanism:

  cow/wraps.json          {"cow_100083b0": "0x100083b0", ...}  -> merged into --wraps by tools/build.py
  runtime/cow/cow_wraps.c sets rt_wrap_cow_<hex> = cow_adapter_<hex> at CRT start

Keys are `cow_<entry hex>` and are stable for ever: renaming a function changes its adapter, its file
and its name in names.csv, never the wrap key, so a wrap already registered by a running host cannot
be orphaned by a rename.

Why a .CRT$XCU initializer instead of an init call: the hosts that have to see our wraps are
build\\boot64.exe (tests/boot64.c), the stand-in FFXiMain.dll (host/ffximain.c) and the 64-bit host -
all upstream files we are not allowed to edit. The MSVC CRT runs every function pointer it finds in
`.CRT$XCU` during start-up for both EXEs and DLLs (we build /MT), so registration happens before any
guest code, without touching a single upstream main().

  python tools/cow/genwraps.py            # regenerate both
  python tools/cow/genwraps.py --check    # fail if they are stale (the gate calls this)
  python tools/cow/genwraps.py --print    # show what would be written
"""
import argparse
import csv
import json
import os
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LEDGER = os.path.join(ROOT, 'ledger', 'functions.csv')
WRAPS_JSON = os.path.join(ROOT, 'cow', 'wraps.json')
REGISTRATION = os.path.join(ROOT, 'runtime', 'cow', 'cow_wraps.c')
HEADER = '/* generated by tools/cow/genwraps.py from ledger/functions.csv - do not edit */\n'


def done_rows(path):
    if not os.path.isfile(path):
        raise SystemExit('no ledger at %s - run python tools/cow/ledger.py' % path)
    with open(path, encoding='utf-8', newline='') as fh:
        rows = list(csv.DictReader(fh))
    out = []
    for r in rows:
        if r['status'] != 'done':
            continue
        entry = r['entry'].lower()
        if entry.startswith('0x'):
            entry = entry[2:]
        if len(entry) != 8 or any(c not in '0123456789abcdef' for c in entry):
            raise SystemExit('ledger: bad entry %r in a done row' % r['entry'])
        if r['thunk'].lower() == 'true':
            raise SystemExit('ledger: %s is a thunk and cannot be a wrap' % r['entry'])
        out.append((entry, r.get('name') or '', r.get('file') or ''))
    return sorted(set(out))


def wraps_json(rows):
    data = {'cow_%s' % e: '0x%s' % e for e, _, _ in rows}
    return json.dumps(data, indent=1, sort_keys=True) + '\n'


def registration(rows):
    lines = [HEADER,
             '/* Our code in front of a generated function. recomp.py --wraps turned f_<hex> into\n'
             '   "if (rt_wrap_<name>) rt_wrap_<name>(g); else f_<hex>_body(g);"; the generated table.c\n'
             '   defines rt_wrap_<name> and points rt_orig_<name> at the body. See docs/cow/STYLE.md for\n'
             '   the adapter contract (arguments in, registers and esp out). */\n',
             '#include <stddef.h>\n',
             '#include "guest.h"\n',
             '#include "runtime.h"\n',
             '#include "funcs.h"\n\n']
    if not rows:
        lines += ['/* nothing converted yet: no wrap to register */\n']
        return ''.join(lines)
    for entry, name, _ in rows:
        lines.append('extern GuestFn rt_wrap_cow_%s;   /* generated table.c */\n' % entry)
    lines.append('\n')
    for entry, name, _ in rows:
        lines.append('void cow_adapter_%s(Guest* g); /* %s%s */\n'
                     % (entry, name or '(unnamed)', '' if not _ else '  ' + _))
    lines.append('\nstatic void cow_install_wraps(void)\n{\n')
    for entry, name, _ in rows:
        lines.append('    rt_wrap_cow_%s = cow_adapter_%s;   /* %s */\n' % (entry, entry, name or 'unnamed'))
    lines.append('}\n\n'
                 '/* MSVC CRT start-up runs every pointer in .CRT$XCU, for EXEs and DLLs alike (/MT),\n'
                 '   so no upstream main() has to call us. */\n'
                 '#pragma section(".CRT$XCU", read)\n'
                 '__declspec(allocate(".CRT$XCU")) void (*cow_wraps_init)(void) = cow_install_wraps;\n')
    return ''.join(lines)


def render(rows):
    return {WRAPS_JSON: wraps_json(rows), REGISTRATION: registration(rows)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ledger', default=LEDGER)
    ap.add_argument('--check', action='store_true', help='exit 1 if the generated files are stale')
    ap.add_argument('--print', dest='show', action='store_true')
    args = ap.parse_args()

    rows = done_rows(args.ledger)
    wanted = render(rows)
    stale = []
    for path, text in wanted.items():
        current = open(path, encoding='utf-8').read() if os.path.isfile(path) else None
        if current != text:
            stale.append(os.path.relpath(path, ROOT))
        if args.show:
            print('===== %s =====\n%s' % (os.path.relpath(path, ROOT), text))
    if args.check:
        if stale:
            print('GENWRAPS STALE: %s (run python tools/cow/genwraps.py)' % ', '.join(stale))
            return 1
        print('GENWRAPS OK: %d wrap(s), both files current' % len(rows))
        return 0
    for path, text in wanted.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if not os.path.isfile(path) or open(path, encoding='utf-8').read() != text:
            with open(path, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(text)
            print('wrote %s' % os.path.relpath(path, ROOT))
        else:
            print('unchanged %s' % os.path.relpath(path, ROOT))
    print('wraps: %d done function(s)' % len(rows))
    return 0


if __name__ == '__main__':
    sys.exit(main())
