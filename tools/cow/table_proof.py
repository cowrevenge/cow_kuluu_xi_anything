"""Prove every row of src/tables/cow_trivial_rows.def against its own generated original.

    python tools/cow/table_proof.py                  # build once, run every row, write cow/table_proof.json
    python tools/cow/table_proof.py --states 64      # fewer fuzzed states per row (default 400)
    python tools/cow/table_proof.py --only 10001370,10002030
    python tools/cow/table_proof.py --check          # exit 1 unless every row is proven in the json

Why one process: the rows share the mapped image, the sandbox and the one DllMain, and 943 links would
be hours of waiting for something the harness answers in minutes. tools/cow/cowdiff.c's --table mode
runs each row's own instrumented body against the adapter the table minted for it, so the proof is still
PER ENTRY - a row is only as good as the states that exercised its own bytes.

The result file is what tools/cow/gate.ps1 reads when it gates a tabled unit: a row with no proof, or a
proof older than the .def, is not a done unit.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import cowdiff                # noqa: E402  build(), instrument(), SITE_RE
import trivial_audit          # noqa: E402  body_index()

TABLE_DEF = os.path.join(ROOT, 'src', 'tables', 'cow_trivial_rows.def')
PROOF = os.path.join(ROOT, 'cow', 'table_proof.json')
ROW_RE = re.compile(r'^COW_TRIVIAL_ROW\(([0-9a-f]{8}),\s*(COW_TRIV_[A-Z_]+),')


def def_hash():
    """sha1 of the .def as it stands - what a proof has to match to still be believed."""
    if not os.path.isfile(TABLE_DEF):
        return ''
    with open(TABLE_DEF, 'rb') as fh:
        return hashlib.sha1(fh.read()).hexdigest()


def rows():
    if not os.path.isfile(TABLE_DEF):
        raise SystemExit('no table - run python tools/cow/mktable.py --write')
    out = []
    with open(TABLE_DEF, encoding='utf-8') as fh:
        for line in fh:
            m = ROW_RE.match(line)
            if m:
                out.append((m.group(1), m.group(2)))
    return out


def render_table(entries):
    """One C file: every row's instrumented original, every row's adapter, and the batch table."""
    index = trivial_audit.body_index()
    L = ['/* generated by tools/cow/table_proof.py from src/tables/cow_trivial_rows.def - do not edit, '
         'do not commit */',
         '#include "funcs.h"',
         '#include "cowdiff_batch.h"',
         '#if defined(_MSC_VER)',
         '#pragma warning(disable: 4102 4189 4101 4702)',
         '#endif',
         '',
         '/* the single-entry globals the harness also expects: in --table mode they are not used, but '
         'they have to exist for the link */',
         'GuestFn cow_side_a, cow_side_b;',
         'unsigned cow_cov[1];',
         'const unsigned cow_cov_count = 0u;',
         'const char* const cow_cov_sites[1] = { "" };',
         'const char* cow_target_entry = "table";',
         'int cow_has_adapter = 1;',
         '']
    table = []
    missing = []
    for entry, _kind in entries:
        body = index.get(entry)
        if body is None:
            missing.append(entry)
            continue
        inst, sites = cowdiff.instrument(body, entry, cov='cow_cov_%s' % entry)
        n = len(sites)
        L.append('/* %s: %d instruction site(s) */' % (entry, n))
        L.append('unsigned cow_cov_%s[%d];' % (entry, n))
        L.append('static const char* const cow_sites_%s[%d] = {' % (entry, n))
        for s in sites:
            L.append('    "%s",' % s.replace('\\', '\\\\').replace('"', "'"))
        L.append('};')
        L.append('static void cow_a_%s(Guest* g)' % entry)
        L += inst[1:]                      # drop the generated `void f_<hex>(Guest* g)` head
        L.append('void cow_adapter_%s(Guest* g);' % entry)
        L.append('')
        table.append('    { "%s", 0x%su, cow_a_%s, cow_adapter_%s, cow_cov_%s, %uu, cow_sites_%s, 1 }'
                     % (entry, entry, entry, entry, entry, n, entry))
    L.append('static const CowBatchRow g_rows[] = {')
    L.append(',\n'.join(table))
    L.append('};')
    L.append('const CowBatchRow* cow_batch_rows = g_rows;')
    L.append('const unsigned cow_batch_count = %du;' % len(table))
    L.append('')
    return '\n'.join(L) + '\n', missing


def build_table(exe_name='table'):
    import build as upstream                                   # tools/build.py, imported not edited
    env = upstream.msvc_env('x64')
    target = os.path.join('build', 'cowdiff', 'cowdiff_target_%s.c' % exe_name)
    exe = os.path.join('build', 'cowdiff', 'cowdiff_%s.exe' % exe_name)
    with cowdiff.harness_lock():
        cowdiff.stale_dependencies()      # a row edit changes the runner without touching its .c mtime
        upstream.recomp('generated/all', ['--all'])
        gen = ['generated\\all\\' + f for f in sorted(os.listdir(cowdiff.GEN)) if f.endswith('.c')]
        objs_a = upstream.compile_stale(env, gen + upstream.PORTABLE, 'build\\all64',
                                       ['/I', 'generated\\all'], upstream.CFLAGS64)
        os.makedirs(cowdiff.COWDIR, exist_ok=True)
        objs_b = upstream.compile_stale(env, ['tools\\cow\\cowdiff.c', target.replace('\\', '/')],
                                       'build\\cowdiff', ['/I', 'generated\\all', '/I', 'tools\\cow'],
                                       upstream.CFLAGS64)
        have = {os.path.basename(o).lower() for o in objs_a}
        objs_b = [o for o in objs_b if os.path.basename(o).lower() not in have]
        cowdiff.stamp_dependencies()
        args = ['/nologo', '/OUT:%s' % exe, '/MACHINE:X64', 'synchronization.lib'] + objs_a + objs_b
        if sum(len(a) + 3 for a in args) > 24000:
            rsp = exe.replace('.exe', '.rsp')
            with open(rsp, 'w', encoding='utf-8') as fh:
                for a in args:
                    fh.write(('"%s"' % a if ' ' in a else a) + '\n')
            upstream.run(['link', '@%s' % rsp], env)
        else:
            upstream.run(['link'] + args, env)
    return exe


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--states', default='400')
    ap.add_argument('--seed', default='12345')
    ap.add_argument('--args', dest='nargs', default='4')
    ap.add_argument('--only', default='', help='comma-separated entries (proof of a subset)')
    ap.add_argument('--check', action='store_true',
                    help='exit 1 unless cow/table_proof.json covers every row with pass=true')
    ap.add_argument('--json', action='store_true')
    a = ap.parse_args()

    want = rows()
    if a.only:
        pick = {x.strip().lower().replace('0x', '') for x in a.only.split(',') if x.strip()}
        want = [r for r in want if r[0] in pick]

    if a.check:
        if not os.path.isfile(PROOF):
            print('TABLE PROOF MISSING: run python tools/cow/table_proof.py')
            return 1
        doc = json.load(open(PROOF, encoding='utf-8'))
        proven = {e: v for e, v in doc.get('rows', {}).items()}
        bad = [e for e, _k in want if not proven.get(e, {}).get('pass')]
        stale = []
        # Content, not mtime: mktable.py --write re-emits the .def on every run, so an mtime check calls a
        # byte-identical table stale and forces a 10-minute re-proof for nothing - while a restore that
        # preserves mtime (git checkout, Copy-Item) can make a genuinely different table look current.
        want_hash = doc.get('table_sha1')
        if not want_hash:
            stale.append('the proof records no table content hash - rerun python tools/cow/table_proof.py')
        elif os.path.isfile(TABLE_DEF) and def_hash() != want_hash:
            stale.append('the .def content (%s) is not what the proof proved (%s) - rerun '
                         'python tools/cow/table_proof.py' % (def_hash()[:12], want_hash[:12]))
        if not bad and not stale:
            print('TABLE PROOF OK %d/%d row(s) proven (states=%s, %s)'
                  % (len(want), len(want), doc.get('states'), doc.get('when')))
            return 0
        for b in bad[:10]:
            print('TABLE PROOF FAIL unproven 0x%s' % b)
        for s in stale:
            print('TABLE PROOF FAIL stale: %s' % s)
        print('TABLE PROOF FAIL %d of %d row(s) unproven' % (len(bad), len(want)))
        return 1

    text, missing = render_table(want)
    if missing:
        print('no generated body for %d row(s): %s' % (len(missing), ', '.join(missing[:5])))
    target = os.path.join(cowdiff.COWDIR, 'cowdiff_target_table.c')
    os.makedirs(cowdiff.COWDIR, exist_ok=True)
    if not os.path.isfile(target) or open(target, encoding='utf-8').read() != text:
        with open(target, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        print('wrote %s (%d row(s))' % (os.path.relpath(target, ROOT).replace('\\', '/'), len(want)))

    t0 = time.time()
    exe = build_table()
    import build as upstream
    b = upstream.__import__('buildinfo').current() if hasattr(upstream, '__import__') else None
    import buildinfo
    b = buildinfo.current()
    cmd = [exe, os.path.join(ROOT, 'generated', 'FFXiMain.retail.dll'), b['game'], '--table',
           '--states', a.states, '--seed', a.seed, '--args', a.nargs, '--json']
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True,
                          encoding='utf-8', errors='replace')
    payload = (proc.stdout or '') + (proc.stderr or '')

    results, summary = {}, None
    for line in payload.splitlines():
        line = line.strip()
        if line.startswith('{'):
            try:
                js = json.loads(line)
            except ValueError:
                continue
            if js.get('table'):
                results[js['entry']] = {'pass': js['pass'], 'states': js['states'],
                                        'mismatches': js['mismatches'], 'reason': js.get('reason', ''),
                                        'blocks': js.get('blocks'), 'blocks_total': js.get('blocks_total')}
        elif line.startswith('COWDIFF TABLE'):
            summary = line
    if not results:
        print(payload.rstrip())
        print('TABLE PROOF FAIL no rows ran (build or harness error above)')
        return 1
    doc = {'when': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
           'states': a.states, 'seed': a.seed,
           'table_sha1': def_hash(),
           'table_mtime': os.path.getmtime(TABLE_DEF) if os.path.isfile(TABLE_DEF) else 0,
           'seconds': round(time.time() - t0, 1),
           'rows': results}
    with open(PROOF, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(doc, fh, indent=1, sort_keys=True)
        fh.write('\n')
    ok = sum(1 for v in results.values() if v['pass'])
    for line in payload.splitlines():
        if line.startswith('COWDIFF FAIL') or line.startswith('  coverage'):
            print(line)
    print('%s rows=%d proven=%d unproven=%d (%.0fs) -> cow/table_proof.json'
          % (summary or 'COWDIFF TABLE', len(results), ok, len(results) - ok, time.time() - t0))
    return 0 if ok == len(results) else 1


if __name__ == '__main__':
    sys.exit(main())
